PORTAL = "https://promote.budget.gov.ru/"


def rule(id, label, ref, field=None, op="manual", value=None):
    return dict(id=id, label=label, field=field, op=op, value=value, source_ref=ref)


def docs(items, ref):
    return [
        dict(id=f"doc-{i+1}", title=title, hint=f"{ref}. {hint}")
        for i, (title, hint) in enumerate(items)
    ]


def entry(
    key,
    title,
    source,
    announcement,
    edition,
    summary,
    benefit,
    conditions,
    documents,
    missing,
    code=None,
    start=None,
    end=None,
    conflict=False,
):
    url = sources[source - 1]["url"]
    text = (ROOT / f"sources/text/{announcement:02}.txt").read_text(encoding="utf-8")
    code = code or re.search(r"Шифр:\s*([^\s]+)", text)[1]
    if not start:
        match = re.search(
            r"(\d{2})\.(\d{2})\.(\d{4}) (\d{2}:\d{2}) - (\d{2})\.(\d{2})\.(\d{4}) (\d{2}:\d{2})",
            text,
        )
        if not match:
            raise ValueError(f"No confirmed dates: {key}")
        a, b, c, d, e, f, g, h = match.groups()
        start = f"{c}-{b}-{a}T{d}:00+03:00"
        end = f"{g}-{f}-{e}T{h}:00+03:00"
    ref = f'{code}, объявление; {edition.split(";")[0]}'[:300]
    missing = missing + [
        "Сверить текущую карточку и изменения отбора на promote.budget.gov.ru; прямой адрес карточки пока не подтверждён.",
        "Завершить редакторскую сверку всех ограничений, приложений и периода применимости редакции.",
    ]
    data = dict(
        summary=summary,
        benefit=benefit,
        operator="Министерство сельского хозяйства Саратовской области",
        obligations="Требуется соглашение и достижение результатов, установленных объявлением и применимой редакцией. Полный перечень обязательств проверяет редактор до публикации.",
        contact="msx@saratov.gov.ru; г. Саратов, ул. Университетская, 45/51, стр. 1",
        rules=conditions
        + [
            rule(
                "remaining",
                "Остальные требования, документы и отсутствие двойного финансирования требуют проверки по первоисточнику",
                ref,
            )
        ],
        documents=docs(documents, ref),
        sources=[
            dict(
                title=f"Официальный комплект: {code}",
                url=url,
                reference=f"Архив source-{source}; текст объявления {announcement:02}.txt",
                published_on="",
            ),
            dict(
                title="Объявления Минсельхоза Саратовской области",
                url=MINAGRO,
                reference=f"Отбор {code}",
                published_on="",
            ),
        ],
        verified_at=None,
        verification_status="conflict" if conflict else "unverified",
        valid_from=None,
        valid_until=None,
        legal_edition=edition,
        research_checked_at=CHECKED,
        missing_evidence=missing,
        verification_notes="Реальная мера, подготовленная по официальному комплекту. Это черновик, а не подтверждение права на субсидию. Дата исследования не является датой полной содержательной проверки. Перечень документов предварительный. Оригиналы и SHA-256 сохранены в data/official/sources. Сканы документов заявителя навигатор не принимает.",
    )
    return dict(
        id=f"saratov-{key}",
        payload=dict(
            title=title,
            category=(
                "grant"
                if key in ("farm", "agromotivator", "agroprogress")
                else "subsidy"
            ),
            synthetic=False,
            data=data,
            rounds=[
                dict(
                    code=code,
                    starts_at=start,
                    ends_at=end,
                    timezone="Europe/Moscow",
                    state="announced",
                    application_url=PORTAL,
                    channel="Электронный бюджет — поиск по шифру",
                )
            ],
        ),
        evidence=dict(
            archive=f"source-{source}",
            announcement_text=f"sources/text/{announcement:02}.txt",
            round_dates_source=(
                "Объявление, раздел «Прием заявок»"
                if announcement != 32
                else "Страница Минсельхоза от 04.08.2026; скан шифра проверен"
            ),
            publication="draft",
        ),
    )


